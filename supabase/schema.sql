create or replace function public.get_active_advertising_feed()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
    return jsonb_build_object(
        'advertisers', (
            select coalesce(
                jsonb_agg(
                    jsonb_build_object(
                        'id', a.id,
                        'company_name', a.company_name,
                        'description', a.description,
                        'logo_url', a.logo_url,
                        'city', a.city,
                        'website', a.website,
                        'status', a.status
                    )
                    order by a.company_name
                ),
                '[]'::jsonb
            )
            from public.advertisers a
            where a.status = 'active'
        ),
        'campaigns', (
            select coalesce(
                jsonb_agg(
                    jsonb_build_object(
                        'id', c.id,
                        'advertiser_name', a.company_name,
                        'name', c.name,
                        'description', c.description,
                        'banner_url', c.banner_url,
                        'landing_url', c.landing_url,
                        'status', c.status,
                        'priority', c.priority,
                        'placement_label', p.label,
                        'placement_slug', p.slug,
                        'start_date', c.start_date,
                        'end_date', c.end_date
                    )
                    order by c.priority, c.start_date
                ),
                '[]'::jsonb
            )
            from public.campaigns c
            join public.advertisers a on a.id = c.advertiser_id
            left join public.ad_placements p on p.id = c.placement_id
            where c.status = 'active'
              and current_date between c.start_date and c.end_date
              and a.status = 'active'
              and (p.id is null or p.active)
        ),
        'placements', (
            select coalesce(
                jsonb_agg(
                    jsonb_build_object(
                        'id', p.id,
                        'slug', p.slug,
                        'label', p.label,
                        'kind', p.kind,
                        'priority', p.priority,
                        'active', p.active
                    )
                    order by p.priority
                ),
                '[]'::jsonb
            )
            from public.ad_placements p
            where p.active = true
        )
    );
end;
$$;

revoke all on function public.get_active_advertising_feed() from public, anon;
grant execute on function public.get_active_advertising_feed() to anon, authenticated;

notify pgrst, 'reload schema';
