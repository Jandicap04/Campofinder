create table if not exists public.usuarios (
    id uuid primary key references auth.users (id) on delete cascade,
    nombre text not null,
    correo text not null unique,
    rol text not null default 'usuario'
        check (rol in ('usuario', 'jugador', 'administrador')),
    bloqueado boolean not null default false,
    creado_en timestamptz not null default now()
);

create table if not exists public.canchas (
    id_cancha bigint generated by default as identity primary key,
    nombre text not null,
    descripcion text,
    precio numeric(10, 2),
    imagen_url text,
    admin_id uuid references public.usuarios (id) on delete set null,
    hora_apertura time not null default time '16:00',
    hora_cierre time not null default time '23:00'
);

alter table public.canchas
    add column if not exists hora_apertura time not null default time '16:00',
    add column if not exists hora_cierre time not null default time '23:00';

do $$
begin
    if not exists (
        select 1 from pg_constraint
        where conrelid = 'public.canchas'::regclass
          and conname = 'canchas_horario_apertura_cierre_check'
    ) then
        alter table public.canchas
            add constraint canchas_horario_apertura_cierre_check
            check (hora_apertura < hora_cierre);
    end if;
end;
$$;

create table if not exists public.reservas (
    id_reserva bigint generated by default as identity primary key,
    id_usuario uuid not null references public.usuarios (id) on delete cascade,
    cancha text not null,
    horario text not null,
    fecha date not null,
    mensaje text not null default '',
    unique (cancha, horario, fecha)
);

create index if not exists reservas_usuario_fecha_idx
    on public.reservas (id_usuario, fecha desc);

create table if not exists public.timers (
    cancha_id bigint primary key references public.canchas (id_cancha) on delete cascade,
    minutos integer not null check (minutos >= 0)
);

create table if not exists public.horarios_bloqueados (
    cancha_id bigint not null references public.canchas (id_cancha) on delete cascade,
    fecha date not null,
    horario text not null,
    primary key (cancha_id, fecha, horario)
);

create table if not exists public.partidos_en_vivo (
    cancha_id bigint primary key references public.canchas (id_cancha) on delete cascade,
    reserva_id bigint references public.reservas (id_reserva) on delete set null,
    equipo_local text not null check (length(btrim(equipo_local)) between 1 and 60),
    equipo_visitante text not null check (length(btrim(equipo_visitante)) between 1 and 60),
    marcador_local integer not null default 0 check (marcador_local >= 0),
    marcador_visitante integer not null default 0 check (marcador_visitante >= 0),
    estado text not null check (estado in ('en_vivo', 'finalizado')),
    iniciado_en timestamptz not null,
    finalizado_en timestamptz,
    check (
        (estado = 'en_vivo' and finalizado_en is null)
        or (estado = 'finalizado' and finalizado_en is not null)
    )
);

alter table public.partidos_en_vivo
    add column if not exists reserva_id bigint
    references public.reservas (id_reserva) on delete set null;

create unique index if not exists partidos_en_vivo_reserva_id_key
    on public.partidos_en_vivo (reserva_id)
    where reserva_id is not null;

create or replace function public.crear_perfil_usuario()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
    insert into public.usuarios (id, nombre, correo)
    values (
        new.id,
        coalesce(new.raw_user_meta_data ->> 'full_name', ''),
        new.email
    );
    return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
    after insert on auth.users
    for each row execute procedure public.crear_perfil_usuario();

create or replace function public.is_active_user()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select exists (
        select 1
        from public.usuarios
        where id = (select auth.uid())
          and bloqueado = false
    );
$$;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select exists (
        select 1
        from public.usuarios
        where id = (select auth.uid())
          and rol = 'administrador'
          and bloqueado = false
    );
$$;

