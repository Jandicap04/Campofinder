grant execute on function public.get_public_court_status(date, time) to anon, authenticated;

create or replace function public.get_court_availability(
    p_court_id bigint,
    p_date date
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
    court_name text;
    blocked_slots jsonb;
    reserved_slots jsonb;
begin
    if not public.is_active_user() then
        raise exception 'Debes iniciar sesión para consultar la disponibilidad.'
            using errcode = '42501';
    end if;

    select nombre into court_name
    from public.canchas
    where id_cancha = p_court_id;

    if court_name is null then
        raise exception 'No encontramos esa cancha.' using errcode = 'P0002';
    end if;

    select coalesce(jsonb_agg(horario order by horario), '[]'::jsonb)
    into blocked_slots
    from public.horarios_bloqueados
    where cancha_id = p_court_id and fecha = p_date;

    select coalesce(jsonb_agg(horario order by horario), '[]'::jsonb)
    into reserved_slots
    from public.reservas
    where cancha = court_name and fecha = p_date;

    return jsonb_build_object(
        'blocked', blocked_slots,
        'reserved', reserved_slots
    );
end;
$$;

create or replace function public.create_reservation(
    p_court_id bigint,
    p_date date,
    p_time text,
    p_message text default ''
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
    court_name text;
    opening_time time;
    closing_time time;
    start_time time;
    end_time time;
    reservation_id bigint;
begin
    if not public.is_active_user() then
        raise exception 'Tu cuenta no puede realizar reservas.'
            using errcode = '42501';
    end if;
    if p_date is null or p_date < current_date then
        raise exception 'La fecha de reserva no es válida.'
            using errcode = '22023';
    end if;
    if p_time is null or p_time !~ '^(1[6-9]|2[0-2]):00 - (1[7-9]|2[0-3]):00$' then
        raise exception 'El horario no es válido.' using errcode = '22023';
    end if;
    start_time := split_part(p_time, ' - ', 1)::time;
    end_time := split_part(p_time, ' - ', 2)::time;
    if end_time - start_time <> interval '1 hour' then
        raise exception 'El horario debe durar una hora.' using errcode = '22023';
    end if;

    select nombre, hora_apertura, hora_cierre
    into court_name, opening_time, closing_time
    from public.canchas
    where id_cancha = p_court_id;
    if court_name is null then
        raise exception 'No encontramos esa cancha.' using errcode = 'P0002';
    end if;
    if start_time < opening_time or end_time > closing_time then
        raise exception 'El horario está fuera del horario de atención de esta cancha.'
            using errcode = '22023';
    end if;
    if length(coalesce(p_message, '')) > 500 then
        raise exception 'El mensaje no puede superar 500 caracteres.'
            using errcode = '22023';
    end if;

    if exists (
        select 1
        from public.horarios_bloqueados
        where cancha_id = p_court_id
          and fecha = p_date
          and horario = p_time
    ) then
        raise exception 'Ese horario está bloqueado.' using errcode = '23505';
    end if;

    insert into public.reservas (id_usuario, cancha, horario, fecha, mensaje)
    values ((select auth.uid()), court_name, p_time, p_date, coalesce(p_message, ''))
    returning id_reserva into reservation_id;

    return reservation_id;
exception
    when unique_violation then
        raise exception 'Ese horario acaba de ser reservado.'
            using errcode = '23505';
end;
$$;

